import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, copyFileSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const source = fileURLToPath(new URL('.', import.meta.url));
const root = process.cwd(), output = resolve(process.argv[2] ?? 'research/vercel-near-client');
const projectFile = process.env.NEAR_PROJECT_FILE ?? join(root, '.vercel/project.json');
const project = JSON.parse(readFileSync(projectFile));
assert.equal(project.projectName, 'next-scriptc');
assert.equal(project.projectId, 'prj_loKFn5UhqXo1q4KesfMY8SZjQzEu');
mkdirSync(output, { recursive: true });
assert(!existsSync(join(output, 'client-deployment.json')), 'Refusing duplicate deployment');
const temporary = mkdtempSync(join(tmpdir(), 'next-scriptc-near-client-'));
try {
  const directory = join(temporary, '.vercel/output/functions/bench.func');
  mkdirSync(directory, { recursive: true });
  copyFileSync(projectFile, join(temporary, '.vercel/project.json'));
  for (const name of ['index.mjs', 'package.json', 'package-lock.json']) copyFileSync(join(source, name), join(directory, name));
  execFileSync('npm', ['ci', '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund'], { cwd: directory, stdio: 'inherit' });
  execFileSync(process.execPath, [join(source, 'test.mjs'), join(directory, 'index.mjs')], { stdio: 'inherit' });
  const config = { runtime: 'nodejs24.x', handler: 'index.mjs', launcherType: 'Nodejs', shouldAddHelpers: false, regions: ['iad1'], memory: 2048, maxDuration: 60 };
  writeFileSync(join(directory, '.vc-config.json'), JSON.stringify(config));
  writeFileSync(join(temporary, '.vercel/output/config.json'), JSON.stringify({ version: 3, routes: [{ src: '/bench', dest: '/bench' }] }));
  const args = ['deploy', '--prebuilt', '--regions', 'iad1', '--environment', 'preview', '--yes', '--json'];
  const result = JSON.parse(execFileSync('vercel', args, { cwd: temporary, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }));
  const d = result.deployment ?? result;
  const row = { id: d.id, url: `https://${d.url.replace(/^https:\/\//, '')}`, acceptedAt: new Date().toISOString(), projectId: project.projectId, config, sourceCommit: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), status: 'accepted' };
  row.sourceSha256 = createHash('sha256').update(readFileSync(join(source, 'index.mjs'))).digest('hex');
  row.lockSha256 = createHash('sha256').update(readFileSync(join(source, 'package-lock.json'))).digest('hex');
  const save = () => writeFileSync(join(output, 'client-deployment.json'), JSON.stringify(row) + '\n');
  save();
  const info = JSON.parse(execFileSync('vercel', ['inspect', row.url, '--json'], { cwd: temporary, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }));
  assert.equal(info.readyState, 'READY'); assert.notEqual(info.target, 'production');
  row.status = 'ready'; row.target = info.target; row.regions = info.regions; save();
  console.log(JSON.stringify(row));
} finally { rmSync(temporary, { recursive: true, force: true }); }
